const assert = require("assert");
const n = require("../../ui/static/normalise.js");
const v = (r) => (r.ok ? r.value : "ERR");
const rate = { kind: "rate" };
assert.strictEqual(v(n.number("9.5%", rate)), 0.095);
assert.strictEqual(v(n.number("0.095", rate)), 0.095);
assert.strictEqual(v(n.number("9.5", rate)), 0.095);
assert.strictEqual(v(n.number("−5%", rate)), -0.05);
assert.strictEqual(v(n.number(" 2 .5 % ".replace(" .", "."), rate)), 0.025);
assert.strictEqual(v(n.number("101", rate)), "ERR");
assert.strictEqual(v(n.number("5%", {})), "ERR");
assert.strictEqual(v(n.number("14x", { kind: "multiple" })), 14);
assert.strictEqual(v(n.number("14×", { kind: "multiple" })), 14);
assert.strictEqual(v(n.number("1,234.5")), 1234.5);
assert.strictEqual(v(n.number("abc")), "ERR");
assert.strictEqual(v(n.number("1e3")), "ERR");
assert.ok(/WACC/.test(n.number("", { label: "WACC" }).error));
assert.strictEqual(v(n.number("", { required: false })), null);
assert.strictEqual(v(n.number("50", { kind: "rate", lo: 0, hi: 0.3, label: "x" })), "ERR");
assert.strictEqual(v(n.ticker(" amd ")), "AMD");
assert.strictEqual(v(n.ticker("a b")), "ERR");
assert.deepStrictEqual(n.tickers("amd, nvda amd").value, ["AMD", "NVDA"]);
assert.strictEqual(n.text("a​  b‮\n c"), "a b c");
assert.strictEqual(n.text("é"), "é");
assert.strictEqual(v(n.noteType("Quarterly Update")), "quarterly_update");
assert.strictEqual(v(n.name("Data  Center")), "Data Center");
assert.strictEqual(v(n.name("<b>")), "ERR");
assert.strictEqual(v(n.ident("../x")), "ERR");
console.log("ok");
