"""Naming parity: references/accounting-definitions.md *is* references/model-schema.json.

Integration stream (A6). The accounting definitions reference is a rendered
projection of A1's authoritative 80-field schema (references/model-schema.json,
generated by scripts/gen_accounting_definitions.py). These tests make drift
impossible in BOTH directions:

  schema id -> must appear in the doc,
  doc id    -> must exist in the schema (no invented ids),
  doc bytes -> must equal a fresh render from the schema.

Segment conventions are additionally pinned:
  - mandate/forecast_bounds keys are the case-sensitive schema names
    (CCG, DCAI, NEX, Foundry, Altera, Mobileye);
  - canonical series ids are the lowercase slugs
    (segments.ccg.revenue, ... per the mapping table);
  - quarterly facts use as-reported full segment names, translated onto the
    canonical ids via references/segment-mapping-v1.json;
  - undistributed remainders live in the optional segments.all_other_* residual
    fields (segments.all_other_revenue / segments.all_other_operating_income).
"""

from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SCHEMA_PATH = ROOT / "references" / "model-schema.json"
DOC_PATH = ROOT / "references" / "accounting-definitions.md"
MAPPING_PATH = ROOT / "references" / "segment-mapping-v1.json"
GENERATOR_PATH = ROOT / "scripts" / "gen_accounting_definitions.py"

BULLET_ID_RE = re.compile(r"^- `([a-z0-9_.]+)` —", re.MULTILINE)


def _load_renderer():
    """Import scripts/gen_accounting_definitions.py without package plumbing."""
    spec = importlib.util.spec_from_file_location("gen_accounting_definitions",
                                                  GENERATOR_PATH)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod


_render_module = _load_renderer()
render = _render_module.render


def schema_ids(schema: dict) -> set[str]:
    """Every id pin-able from the schema, segments expanded like the engine."""
    ids: set[str] = set()
    for key, group in schema["statements"].items():
        if key == "segments":
            slugs = [s.lower() for s in group["segments"]]
            for seg in slugs:
                for field in group["per_segment_fields"]:
                    ids.add(f"segments.{seg}.{field['suffix']}")
            for resid in group.get("residuals", []):
                ids.add(resid["id"])
        else:
            for field in group["fields"]:
                ids.add(field["id"])
    for metric in schema.get("derived_metrics", []):
        ids.add(metric["id"])
    return ids


def doc_ids(text: str) -> set[str]:
    return set(BULLET_ID_RE.findall(text))


def test_every_schema_id_appears_in_definitions_doc():
    schema = json.loads(SCHEMA_PATH.read_text("utf-8"))
    doc = DOC_PATH.read_text("utf-8")
    missing = schema_ids(schema) - doc_ids(doc)
    assert not missing, (
        f"model-schema.json ids missing from accounting-definitions.md: "
        f"{sorted(missing)} — regenerate with "
        "scripts/gen_accounting_definitions.py")


def test_every_doc_id_exists_in_schema():
    schema = json.loads(SCHEMA_PATH.read_text("utf-8"))
    doc = DOC_PATH.read_text("utf-8")
    invented = doc_ids(doc) - schema_ids(schema)
    assert not invented, (
        f"accounting-definitions.md cites ids that model-schema.json does "
        f"not define: {sorted(invented)} — the doc must be a strict "
        "projection of the schema")


def test_definitions_doc_is_a_fresh_render_of_the_schema():
    """Byte parity with the generator: nobody hand-edited either side."""
    schema = json.loads(SCHEMA_PATH.read_text("utf-8"))
    assert DOC_PATH.read_text("utf-8") == render(schema), (
        "accounting-definitions.md differs from a regeneration from "
        "model-schema.json — run scripts/gen_accounting_definitions.py and "
        "commit the result (or update the generator)")


def test_statement_field_counts_match_schema_note():
    """80 primary fields: IS 18 + BS 22 + CF 16 + segments 6x4 (+2 residuals)."""
    schema = json.loads(SCHEMA_PATH.read_text("utf-8"))
    counts = {k: len(g["fields"]) for k, g in schema["statements"].items()
              if k != "segments"}
    assert counts == {"income_statement": 18, "balance_sheet": 22,
                      "cash_flow": 16}
    ids = schema_ids(schema)
    for seg in ("ccg", "dcai", "nex", "foundry", "altera", "mobileye"):
        for suffix in ("revenue", "operating_income", "operating_margin",
                       "revenue_share_of_total"):
            assert f"segments.{seg}.{suffix}" in ids
    assert "segments.all_other_revenue" in ids
    assert "segments.all_other_operating_income" in ids


def test_segment_conventions_documented_and_consistent_with_engine():
    """Doc + schema + mapping table + engine agree on the segment naming."""
    schema = json.loads(SCHEMA_PATH.read_text("utf-8"))
    doc = DOC_PATH.read_text("utf-8")
    mapping = json.loads(MAPPING_PATH.read_text("utf-8"))

    schema_names = schema["statements"]["segments"]["segments"]
    assert schema_names == ["CCG", "DCAI", "NEX", "Foundry", "Altera",
                            "Mobileye"]
    # mandate forecast_bounds keys are the case-sensitive schema names
    assert mapping["canonical_series"]["segments"] == schema_names
    canonical_slugs = [s.lower() for s in schema_names]

    from coverageflow.model_engine import mapping_segment_slugs
    assert sorted(mapping_segment_slugs(mapping)) == sorted(canonical_slugs), (
        "model_engine canonical slugs and schema segment names disagree")

    # the doc pins both conventions and the translation table
    for name in schema_names + canonical_slugs:
        assert name in doc, f"segment name {name!r} missing from the doc"
    assert "segment-mapping-v1.json" in doc
    assert "as-reported" in doc.lower()
    assert "segments.Client Computing Group.revenue" in doc


def test_mapping_table_canonical_rules_target_schema_segments():
    """Every canonical value in the mapping table lands on a schema segment."""
    schema = json.loads(SCHEMA_PATH.read_text("utf-8"))
    slugs = {s.lower() for s in schema["statements"]["segments"]["segments"]}
    mapping = json.loads(MAPPING_PATH.read_text("utf-8"))
    for period, entry in mapping["periods"].items():
        for rule in entry.get("rules", []):
            canon = rule.get("canonical")
            for c in (canon if isinstance(canon, list) else [canon]):
                if c is None or c.startswith("segments."):
                    continue
                assert c in slugs, (
                    f"mapping rule for {period} targets unknown canonical "
                    f"segment {c!r}")
